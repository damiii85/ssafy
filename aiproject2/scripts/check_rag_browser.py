"""기존 UI 안에서 자연어 탐색 → 항목 선택 → 근거 기반 대화 → 기록 복원 검증."""
import argparse
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

parser=argparse.ArgumentParser()
parser.add_argument('--url',default='http://localhost:8502')
args=parser.parse_args()
out=Path('data/processed/ui_preview');out.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=r'C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe',headless=True)
    page=browser.new_page(viewport={'width':1550,'height':1040})
    page.goto(args.url)
    page.get_by_role('button',name='분석 시작하기').click()
    search=page.get_by_role('textbox',name='지역 검색')
    search.fill('카페가 100곳 이상인 지역');search.press('Enter')
    expect(page.locator('.st-key-region-grid')).not_to_contain_text('수성못')
    expect(page.locator('.st-key-region-grid')).to_contain_text('조건 일치 업종')
    page.screenshot(path=str(out/'25_natural_region_search.png'))
    search.fill('수성못에서 카페 업종을 찾아줘');search.press('Enter')
    expect(page.locator('.st-key-region-grid [class*="st-key-spot-card-"]')).to_have_count(1)
    page.get_by_role('button',name='수성못',exact=True).click()
    feed=page.locator('.st-key-chat-feed')
    expect(feed).to_contain_text('참고 자료',timeout=45000)
    expect(feed).to_contain_text('[근거 1]')
    expect(feed).to_contain_text('95곳')
    expect(feed).to_contain_text('2026-07')
    detail=feed.locator('details').filter(has=page.locator('summary',has_text='상세 근거 및 분석 기준'))
    detail.locator('summary').click()
    page.wait_for_function('e=>e.open',arg=detail.element_handle())
    feed.evaluate('e=>e.scrollTop=e.scrollHeight')
    page.screenshot(path=str(out/'25_numbered_sources.png'))
    detail.locator('summary').click()
    page.wait_for_function('e=>!e.open',arg=detail.element_handle())
    prompt=page.get_by_placeholder('궁금한 내용을 자유롭게 질문해 주세요.')
    prompt.fill('오늘 실시간 임대료는?');prompt.press('Enter')
    expect(page.locator('[class*="st-key-answer-card-"]')).to_have_count(2,timeout=45000)
    expect(feed).to_contain_text('알 수 없',timeout=30000)
    # 자료 확인 상태는 상세 영역에만 남고 기본 화면에는 노출하지 않는다.
    for notice in feed.get_by_text('API 키/연결 설정',exact=False).all():
        expect(notice).not_to_be_visible()
    assert page.locator('[data-testid="stException"]').count()==0
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    page.get_by_role('button',name='새 대화하기').click()
    page.get_by_role('button',name='수성못',exact=True).click()
    page.locator('.st-key-archive_0 button').click()
    expect(feed).to_contain_text('참고 자료',timeout=30000)
    expect(feed).to_contain_text('오늘 실시간 임대료는?')
    page.set_viewport_size({'width':390,'height':844})
    page.wait_for_timeout(300)
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    page.screenshot(path=str(out/'25_mobile_citations.png'))
    browser.close()
print('Natural-language region conditions, selection context, citations, abstention, archived history and mobile passed.')
